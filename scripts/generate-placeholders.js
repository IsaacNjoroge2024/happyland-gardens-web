/**
 * Generates per-image blur placeholder data URLs for all WebP images.
 * Run: npm run generate-placeholders  (always run after optimize-images)
 *
 * Output: lib/image-placeholders.ts — a Record<string, string> map of
 *   "/images/gallery/foo.webp" → "data:image/webp;base64,..."
 *
 * ImageWrapper imports this map for colour-accurate per-image blur previews.
 */

const { findFiles } = require("./utils");
const sharp = require("sharp");
const fs = require("fs");
const path = require("path");

const PUBLIC_IMAGES_DIR = path.join(process.cwd(), "public", "images");
const OUTPUT_PATH = path.join(process.cwd(), "lib", "image-placeholders.ts");

async function generatePlaceholders() {
  console.log("🎨 Generating image placeholders...\n");

  const webpFiles = findFiles(PUBLIC_IMAGES_DIR, ".webp");
  const placeholders = {};

  for (const webpPath of webpFiles) {
    // Convert absolute path to the public URL path (forward slashes, no "public" prefix)
    const relativePath = path.relative(path.join(process.cwd(), "public"), webpPath);
    const urlPath = "/" + relativePath.replace(/\\/g, "/");

    const { data } = await sharp(webpPath)
      .resize(8, 8, { fit: "cover" })
      .webp({ quality: 20 })
      .toBuffer({ resolveWithObject: true });

    placeholders[urlPath] = `data:image/webp;base64,${data.toString("base64")}`;
    console.log(`✓  ${urlPath}`);
  }

  // Sort entries for consistent, diff-friendly output
  const sortedEntries = Object.entries(placeholders).sort(([a], [b]) => a.localeCompare(b));

  const fileContent =
    `// Auto-generated by scripts/generate-placeholders.js\n` +
    `// Run: npm run generate-placeholders\n` +
    `// Do not edit manually\n\n` +
    `export const imagePlaceholders: Record<string, string> = {\n` +
    sortedEntries
      .map(([key, value]) => `  ${JSON.stringify(key)}: ${JSON.stringify(value)},`)
      .join("\n") +
    `\n};\n`;

  fs.writeFileSync(OUTPUT_PATH, fileContent, "utf-8");
  console.log(`\n✅ Done: ${sortedEntries.length} placeholders → lib/image-placeholders.ts`);
}

generatePlaceholders().catch((err) => {
  console.error("❌ Placeholder generation failed:", err);
  process.exit(1);
});
